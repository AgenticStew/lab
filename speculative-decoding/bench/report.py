#!/usr/bin/env python3
"""Build RESULTS.md and results.json from results/*/row.json.

Per row and prompt: median decode tok/s (client-measured), speedup over the same model's no-guesser row, share of
guesses accepted, mean tokens per verify step, VRAM added over the desktop's reading, and how much of the greedy
answer matches the no-guesser answer (exact, or % of characters before the first difference).
"""
import json, statistics, sys
from pathlib import Path

B = Path(__file__).resolve().parent
RES = B / "results"
PROMPTS = ["code", "edit", "explain", "story", "json"]


def base_of(label):
    """The no-guesser row a row is compared with: same model, tier, GPU-layer count, sampling and run batch."""
    parts = label.split("-")
    if parts[0] == "nuc":                   # rows from the RTX 3080 Ti: nuc-<model>-<guesser>[-ngl..]
        parts = ["nuc-" + parts[1]] + [p for p in parts[2:] if not p.startswith("ngl")]
    model = parts[0]
    suffix = "".join("-" + p for p in parts if p.startswith(("ngl", "t0", "t1")) or p in ("think", "v1", "recheck"))
    tier = next((p for p in parts if p.endswith("gb")), None)
    if tier:
        return f"{model}-{tier}-none{suffix}"
    return f"{model}-none{suffix}"


def load():
    rows = {}
    for f in sorted(RES.glob("*/row.json")):
        r = json.loads(f.read_text())
        r["label"] = f.parent.name          # the folder name: kept *-v1 copies carry their old label inside
        if r["label"].endswith("-smoke") or r["label"].startswith(("diag-", "cal-", "cal2-", "replay-")) or "--" in r["label"]:
            continue
        rows[r["label"]] = r
    return rows


def summarize(r):
    out = {}
    for p, runs in (r.get("runs") or {}).items():
        tps = [x["tps"] for x in runs if x.get("tps")]
        x = runs[0]
        out[p] = {"tps": statistics.median(tps) if tps else None, "runs": len(runs), "n": x["n"],
                  "accept": x.get("accept_rate"), "mean_len": x.get("mean_len"), "text": x["text"],
                  "deterministic": len({y["sha"] for y in runs}) == 1, "finish": x.get("finish")}
    return out


def same_prefix(a, b):
    i = next((k for k in range(min(len(a), len(b))) if a[k] != b[k]), min(len(a), len(b)))
    return 100.0 * i / max(len(a), 1)


def main():
    rows = load()
    S = {k: summarize(v) for k, v in rows.items()}
    table = []
    for k, r in rows.items():
        b = base_of(k)
        rec = {"label": k, "status": r.get("status"), "load_s": r.get("load_s"), "vram_delta_mib": r.get("vram_delta_mib"),
               "base": b if b in S and b != k else None, "prompts": {}}
        for p, s in S[k].items():
            e = {kk: s[kk] for kk in ("tps", "runs", "n", "accept", "mean_len", "deterministic", "finish")}
            if rec["base"] and p in S[b] and s["tps"] and S[b][p]["tps"]:
                e["speedup"] = s["tps"] / S[b][p]["tps"]
                e["identical"] = s["text"] == S[b][p]["text"]
                e["same_prefix_pct"] = same_prefix(S[b][p]["text"], s["text"])
            rec["prompts"][p] = e
        table.append(rec)
    (B / "results.json").write_text(json.dumps(table, indent=1))

    L = ["# RESULTS: speculative decoding on one RTX 5090", "",
         "Generated by `report.py` from `results/*/row.json`. llama.cpp b12189 (80d2c0c2c, CUDA, sm_120), greedy (top-k 1),",
         "thinking off, batch 1, 8K context, flash attention, 512-token cap. Decode tok/s = (tokens - 1) / (last - first",
         "streamed chunk), median of the runs shown. Speedup is against the same model's no-guesser row. Accept = share of",
         "guessed tokens the big model kept; tokens/check = tokens produced per verify step. Same answer = the greedy reply",
         "matches the no-guesser reply exactly (otherwise the % of characters before the first difference).", ""]
    groups = {}
    for rec in table:
        g = rec["label"].split("-")
        groups.setdefault(g[0] + ("-" + g[1] if g[0] == "nuc" else ""), []).append(rec)
    for g, recs in groups.items():
        L += [f"## {g}", "", "| Row | Status | VRAM +GiB | " + " | ".join(PROMPTS) + " |",
              "|---|---|---|" + "---|" * len(PROMPTS)]
        for rec in recs:
            cells = []
            for p in PROMPTS:
                e = rec["prompts"].get(p)
                if not e or not e.get("tps"):
                    cells.append("—")
                    continue
                c = f"{e['tps']:.1f}"
                if e.get("speedup"):
                    c += f" ({e['speedup']:.2f}x)"
                if e.get("accept") is not None:
                    c += f"<br>acc {e['accept']*100:.0f}% · {e['mean_len']:.2f}/check"
                if "identical" in e:
                    c += "<br>same" if e["identical"] else f"<br>same to {e['same_prefix_pct']:.0f}%"
                cells.append(c)
            v = rec.get("vram_delta_mib")
            L.append(f"| {rec['label']} | {rec['status']} | {v/1024:.2f} | " % () if False else
                     f"| {rec['label']} | {rec['status']} | {(v or 0)/1024:.2f} | " + " | ".join(cells) + " |")
        L.append("")
    (B / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
